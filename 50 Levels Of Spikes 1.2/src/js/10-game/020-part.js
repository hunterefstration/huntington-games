function handleKey(e, isDown) {
    if (e.code === 'ArrowLeft' || e.code === 'KeyA') keys.left = isDown;
    if (e.code === 'ArrowRight' || e.code === 'KeyD') keys.right = isDown;
    if (e.code === 'ArrowUp' || e.code === 'KeyW' || e.code === 'Space') {
        if (isDown && !keys.jump) player.jumpBufferTimer = 8;
        keys.jump = isDown;
    }
}


function isTyping(e) {
    const t = e.target;
    return t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA');
}


window.addEventListener('keydown', (e) => {
    if (!modal.classList.contains('hidden')) {
        if (e.code === 'Escape') { closeModal(); e.preventDefault(); }
        return;
    }
    if (gameState === 'PLAYING') {
        if (e.code === 'Escape' || e.code === 'KeyP') { pauseGame(); e.preventDefault(); return; }
        handleKey(e, true);
        if (GAME_KEYS[e.code]) e.preventDefault();
    } else if (gameState === 'DEAD') {
        // quick retry works straight away, not only once the death screen fades in (held-key repeats are ignored)
        if ((e.code === 'Enter' || e.code === 'KeyR') && !e.repeat) { e.preventDefault(); retryLevel(); }
    } else if (gameState === 'PAUSED') {
        if (e.code === 'Escape' || e.code === 'KeyP') { e.preventDefault(); resumeGame(); }
    } else if (gameState === 'CLEARED') {
        if (e.code === 'Enter' && !clearScreen.classList.contains('hidden')) { e.preventDefault(); replayCustom(); }
    } else if (gameState === 'EDITOR') {
        if (!isTyping(e)) editorKey(e);
    }
});
window.addEventListener('keyup', (e) => handleKey(e, false));
window.addEventListener('blur', () => { keys.left = keys.right = keys.jump = false; });


function setupTouch(id, keyProp) {
    const btn = document.getElementById(id);
    const press = (e) => {
        e.preventDefault();
        keys[keyProp] = true;
        btn.classList.add('active');
        if (keyProp === 'jump') player.jumpBufferTimer = 8;
    };
    const release = (e) => {
        e.preventDefault();
        keys[keyProp] = false;
        btn.classList.remove('active');
    };
    btn.addEventListener('touchstart', press, {passive: false});
    btn.addEventListener('touchend', release, {passive: false});
    btn.addEventListener('touchcancel', release, {passive: false});
}


setupTouch('btnLeft', 'left');
setupTouch('btnRight', 'right');
setupTouch('btnJump', 'jump');
